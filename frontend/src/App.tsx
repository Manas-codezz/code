import { useEffect, useState } from 'react'
import { loadAuth, logout, type User } from './api'
import Login from './pages/Login'
import Dashboard from './pages/Dashboard'
import Review from './pages/Review'
import KB from './pages/KB'

type Route = 'login' | 'dashboard' | 'review' | 'kb'

function parseHash(): { route: Route; arg: string } {
  const h = location.hash.replace(/^#\/?/, '')
  const [head, arg = ''] = h.split('/')
  if (head === 'review') return { route: 'review', arg }
  if (head === 'kb') return { route: 'kb', arg }
  if (head === 'login') return { route: 'login', arg }
  return { route: 'dashboard', arg }
}

const NAV: { id: Route; label: string; need: number }[] = [
  { id: 'dashboard', label: 'Dashboard', need: 0 },
  { id: 'review', label: 'Review queue', need: 0 },
  { id: 'kb', label: 'Knowledge base', need: 0 },
]

// role rank for nav gating hints (KB edit UI hides below manager)
export const ROLE_RANK: Record<User['role'], number> = {
  creator: 0, reviewer: 1, manager: 2, admin: 3,
}

export default function App() {
  const [path, setPath] = useState(parseHash())
  const [user, setUser] = useState<User | null>(loadAuth()?.user ?? null)

  useEffect(() => {
    const on = () => setPath(parseHash())
    addEventListener('hashchange', on)
    if (!location.hash) location.hash = '#/dashboard'
    return () => removeEventListener('hashchange', on)
  }, [])

  // session died -> back to login
  useEffect(() => {
    if (!user && path.route !== 'login') location.hash = '#/login'
    if (user && path.route === 'login') location.hash = '#/dashboard'
  }, [user, path.route])

  if (path.route === 'login' || !user) {
    return <Login onLogin={setUser} />
  }

  return (
    <div className="min-h-screen flex bg-paper text-ink">
      {/* left rail */}
      <aside className="w-52 shrink-0 border-r border-hairline bg-surface
        flex flex-col fixed inset-y-0 left-0">
        <div className="px-5 py-5 border-b border-hairline flex items-baseline
          gap-2">
          <span className="w-3 h-3 bg-accent rounded-sm inline-block
            translate-y-[-1px]" />
          <span className="font-semibold tracking-tight text-[15px]">
            BrandGuard
          </span>
        </div>
        <nav className="flex-1 py-3">
          {NAV.map((n) => {
            const active = path.route === n.id
            return (
              <a key={n.id} href={`#/${n.id}`}
                 className={`block px-5 py-2 text-sm border-l-2 transition-colors
                   ${active
                     ? 'border-accent text-ink font-medium bg-orange-50/40'
                     : 'border-transparent text-ink2 hover:text-ink hover:bg-paper'}`}>
                {n.label}
              </a>
            )
          })}
        </nav>
        <div className="px-5 py-4 border-t border-hairline">
          <div className="text-[13px] truncate font-medium">{user.email}</div>
          <div className="eyebrow mt-0.5">{user.role} · {user.team}</div>
          <button onClick={() => { logout(); setUser(null) }}
                  className="mt-2 text-[12px] text-accent hover:underline">
            Sign out
          </button>
        </div>
      </aside>

      {/* main */}
      <div className="flex-1 ml-52 min-w-0">
        {/* AI disclosure strip — required by governance docs */}
        <div className="border-b border-hairline bg-surface px-6 py-2
          flex items-center gap-3 text-[12px] text-ink2">
          <span className="w-1.5 h-1.5 rounded-full bg-accent inline-block" />
          <span>
            <strong className="text-ink font-semibold">AI advisory</strong>
            {' — findings are generated by an LLM + rule engine; '}
            a human always makes the final approval.
          </span>
        </div>

        <main className="px-6 py-6 max-w-6xl">
          {path.route === 'dashboard' && <Dashboard />}
          {path.route === 'review' && <Review key={path.arg || 'list'}
                                              selected={path.arg} />}
          {path.route === 'kb' && <KB user={user} />}
        </main>
      </div>
    </div>
  )
}
